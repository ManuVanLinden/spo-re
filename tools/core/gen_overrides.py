"""Generate runtime/core/src/core_overrides.c: strong sg_imp_<dll>_<name> definitions that
tail-call the core's shims, for use when runtime/hle's generated stubs are weak
(tools/hle/gen_thunks.py emits them so; runtime/win32 relies on the same).
Then every path reaches the core: the translator's direct SG_CALL(sg_imp_...) calls, the IAT and
GetProcAddress. Off unless SG_CORE_OVERRIDE_HLE_STUBS=1 (runtime/core/Makefile detects weak stubs).

Skipped: symbols runtime/hle implements by hand (strong in runtime/hle/src) and symbols runtime/win32
overrides (runtime/win32/src/w32_overrides.c; CloseHandle is runtime/win32's and forwards core handles
through w32_close_foreign), so no symbol is defined twice.

Usage:   python3 -P tools/core/gen_overrides.py [--check]
Inputs:  the X() shim table of runtime/core/src/core_shims.c, runtime/win32/src/w32_overrides.c and
         data/hle/imports-table.json (from tools/hle/gen_thunks.py)
Outputs: runtime/core/src/core_overrides.c (tracked)
When:    after adding or removing a shim in core_shims.c's table.
"""
import json
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
OUT = os.path.join(ROOT, "runtime", "core", "src", "core_overrides.c")


def main():
    shims = re.findall(r'X\((\w+), (\w+), "(sg_imp_[^"]+)", \d+\)',
                       open(os.path.join(ROOT, "runtime", "core", "src", "core_shims.c")).read())
    table = json.load(open(os.path.join(ROOT, "data", "hle", "imports-table.json")))
    hle = {r["symbol"]: r for r in table["imports"] if r.get("symbol")}
    w32 = set()
    p = os.path.join(ROOT, "runtime", "win32", "src", "w32_overrides.c")
    if os.path.exists(p):
        w32 = {"sg_imp_%s_%s" % m for m in re.findall(r"SG_IMPORT\((\w+), (\w+)\)", open(p).read())}
    rows, skipped = [], []
    for dll, name, sym in shims:
        if sym not in hle:
            skipped.append((sym, "not an HLE import"))
        elif hle[sym]["implemented"]:
            skipped.append((sym, "runtime/hle implements it"))
        elif sym in w32:
            skipped.append((sym, "runtime/win32 overrides it"))
        else:
            rows.append((dll, name, sym))
    lines = ["/* GENERATED by tools/core/gen_overrides.py. Do not edit.",
             " *",
             " * Strong definitions of runtime/hle's import symbols that tail-call the core's shims. They replace",
             " * runtime/hle's generated stubs once those are weak (tools/hle/gen_thunks.py emits them so),",
             " * so translated code's direct SG_CALL(sg_imp_...) calls reach the core. Off by default: the",
             " * build sets SG_CORE_OVERRIDE_HLE_STUBS=1 when gen/hle_imports.c has weak stubs.",
             " * %d overrides; skipped: %s. */" % (len(rows), ", ".join("%s (%s)" % s for s in skipped) or "none"),
             '#include "core_internal.h"', "",
             "#ifndef SG_CORE_OVERRIDE_HLE_STUBS", "#define SG_CORE_OVERRIDE_HLE_STUBS 0", "#endif",
             "const int sg_core_overrides_linked = SG_CORE_OVERRIDE_HLE_STUBS;", "",
             "#if SG_CORE_OVERRIDE_HLE_STUBS"]
    for dll, name, sym in rows:
        lines.append("SGC_SHIM(%s, %s);" % (dll, name))
    for dll, name, sym in rows:
        lines.append("void %s(sg_ctx *SG_RESTRICT ctx, uint8_t *mem) { SG_TAILCALL(sgc_%s_%s); }" % (sym, dll, name))
    lines += ["#endif", ""]
    text = "\n".join(lines)
    if "--check" in sys.argv:
        sys.exit(0 if os.path.exists(OUT) and open(OUT).read() == text else 1)
    open(OUT, "w").write(text)
    print("%d overrides -> %s; skipped %d" % (len(rows), os.path.relpath(OUT, ROOT), len(skipped)))
    for s in skipped:
        print("  skipped %s: %s" % s)


if __name__ == "__main__":
    main()
