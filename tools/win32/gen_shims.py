#!/usr/bin/env python3
"""Generate runtime/win32/src/w32_shims.h and w32_overrides.c from the W32_IMPORT definitions in runtime/win32/src.

For every `W32_IMPORT(dll, sym) { ... }` it records the stack clean-up the body performs: every
SG_RET(n), SG_RETURN_STDCALL(v, n), SG_RETURN_CDECL(v) (n = 0) and SG_RETURN_U64(v, n) in the
body must agree. Bodies without a return (exit, _exit) count as 0. The header lists
(dll stem, DLL name, export name, symbol, clean-up) for w32_register_shims(), which checks the
clean-up against runtime/hle's import table at run time; this script also checks it against
data/hle/imports-table.json and fails on a mismatch.

Usage:   python3 tools/win32/gen_shims.py [--check]   (`make -C runtime/win32 gen` / `check-gen`)
Inputs:  runtime/win32/src/*.c and data/hle/imports-table.json (from tools/hle/gen_thunks.py)
Outputs: runtime/win32/src/w32_shims.h and runtime/win32/src/w32_overrides.c (tracked)
When:    after adding or changing a W32_IMPORT shim.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "runtime/win32/src"
OUT = SRC / "w32_shims.h"
OUT_OVR = SRC / "w32_overrides.c"
TABLE = ROOT / "data/hle/imports-table.json"

DLL_NAMES = {"kernel32": "KERNEL32.dll", "msvcr90": "MSVCR90.dll", "advapi32": "ADVAPI32.dll",
             "shell32": "SHELL32.dll", "version": "VERSION.dll"}
EXPORT_NAMES = {("msvcr90", "new"): "??2@YAPAXI@Z", ("msvcr90", "delete"): "??3@YAXPAX@Z"}


def bodies(text):
    for m in re.finditer(r"W32_IMPORT\((\w+),\s*(\w+)\)\s*\{", text):
        i, depth = m.end(), 1
        while depth:
            c = text[i]
            depth += c == "{"
            depth -= c == "}"
            i += 1
        yield m.group(1), m.group(2), text[m.end():i - 1]


def cleanup_of(body):
    vals = set()
    for m in re.finditer(r"SG_RET\(\s*(\d+)\s*\)", body):
        vals.add(int(m.group(1)))
    for m in re.finditer(r"SG_RETURN_(?:STDCALL|U64)\((.*?),\s*(\d+)\s*\);", body):
        vals.add(int(m.group(2)))
    if re.search(r"SG_RETURN_CDECL\(", body):
        vals.add(0)
    return vals


def main():
    shims, errors = [], []
    for f in sorted(SRC.glob("*.c")):
        for dll, sym, body in bodies(f.read_text()):
            vals = cleanup_of(body)
            if len(vals) > 1:
                errors.append(f"{f.name}: {dll}!{sym} returns with different clean-ups {sorted(vals)}")
                continue
            n = vals.pop() if vals else 0
            if not vals and dll != "msvcr90" and n == 0 and "SG_RET" not in body:
                errors.append(f"{f.name}: {dll}!{sym} has no return")
            shims.append((dll, sym, n, f.name))
    table = json.loads(TABLE.read_text())["imports"]
    index = {(i["dll"].lower().removesuffix(".dll"), i["name"]): i for i in table if i["name"]}
    lines, overrides = [], []
    imported = 0
    for dll, sym, n, fname in shims:
        export = EXPORT_NAMES.get((dll, sym), sym)
        imp = index.get((dll, export))
        if imp:
            imported += 1
            overrides.append(f"SG_IMPORT({dll}, {export}) {{ SG_TAILCALL(w32_imp_{dll}_{sym}); }}")
            want = imp["cleanup_bytes"] if imp["cc"] == "stdcall" else 0
            if want != n:
                errors.append(f"{fname}: {dll}!{sym} pops {n} bytes; imports-table.json says {want}")
        lines.append(f'    X({dll}, "{DLL_NAMES[dll]}", "{export}", {sym}, {n}) \\')
    decls = "\n".join(f"W32_IMPORT({d}, {s});" for d, s, _, _ in shims)
    text = f"""/* GENERATED by tools/win32/gen_shims.py from the W32_IMPORT definitions in runtime/win32/src.
 * Do not edit. {len(shims)} shims, {imported} of them for imports of this exe. */
#ifndef SPORE_W32_SHIMS_H
#define SPORE_W32_SHIMS_H
#include "w32.h"

{decls}

/* X(dll stem, DLL name, export name, symbol suffix, stack clean-up bytes) */
#define W32_SHIM_LIST(X) \\
{chr(10).join(lines)}

typedef struct w32_shim {{ const char *dll, *name; sg_func *fn; unsigned cleanup; }} w32_shim;
extern const w32_shim w32_shims[];
extern const unsigned w32_shim_count;
#endif
"""
    ovr = f"""/* GENERATED by tools/win32/gen_shims.py. Do not edit.
 *
 * Translated code calls imports by symbol (SG_CALL(sg_imp_..., ra), SG_TAILCALL(sg_imp_...)),
 * so swapping hle_imports[].fn reaches only IAT-indirect calls and GetProcAddress. When
 * runtime/hle's generated stubs are weak (tools/hle/gen_thunks.py emits them so),
 * these strong definitions replace them at link time for every path. The Makefile turns
 * W32_OVERRIDE_HLE_STUBS on by itself once gen/hle_imports.c has weak stubs.
 * {len(overrides)} imports. */
#include "w32_shims.h"

#ifndef W32_OVERRIDE_HLE_STUBS
#define W32_OVERRIDE_HLE_STUBS 0
#endif
/* referenced by w32_init.c so this archive member is always linked */
const int w32_overrides_linked = W32_OVERRIDE_HLE_STUBS;

#if W32_OVERRIDE_HLE_STUBS
{chr(10).join(overrides)}
#endif
"""
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text or not OUT_OVR.exists() or OUT_OVR.read_text() != ovr:
            print("w32_shims.h is stale; run tools/win32/gen_shims.py", file=sys.stderr)
            return 1
        print(f"up to date: {len(shims)} shims, {imported} imported")
        return 0
    OUT.write_text(text)
    OUT_OVR.write_text(ovr)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(shims)} shims, {imported} for imports")
    return 0


if __name__ == "__main__":
    sys.exit(main())
