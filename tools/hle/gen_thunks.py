"""Generate the HLE import table and "unimplemented" stubs.

Inputs:  data/imports.json (495 imports, IAT addresses), tools/hle/sigs.py (conventions and the
         dynamically resolved names), runtime/hle/src/*.c (hand-written shims: any
         `SG_IMPORT(dll, name) {` definition there suppresses the generated stub).
Outputs: runtime/hle/gen/hle_imports.h   symbol declarations + HLE_IMP_* indices
         runtime/hle/gen/hle_imports.c   sg_import hle_imports[], hle_import_info[],
                                         hle_dynamics[], and one stub per unimplemented entry
         data/hle/imports-table.json     IAT slot -> host symbol, convention, clean-up (git-ignored; read by
                                         tools/win32/gen_shims.py and tools/core/gen_overrides.py)

Naming follows spore_guest.h section 7: sg_imp_<DLL stem lower-case>_<export name or ordN>.
Two MSVCR90 exports are C++-mangled; non-identifier characters become '_' (cname).

Usage:   python3 tools/hle/gen_thunks.py [--check]   (--check: fail if the outputs are stale; `make -C runtime/hle gen`
         and `check-gen` run the two)
When:    after adding a shim to runtime/hle/src or editing sigs.py; needs data/imports.json in the source tree
         (tools/imports/build_table.py run by hand; the converter writes its copy into its work folder).
"""
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)
import sigs  # noqa: E402

CC = {"c": "SG_CC_CDECL", "s": "SG_CC_STDCALL", "t": "SG_CC_THISCALL", "x": "SG_CC_X87", "d": "HLE_CC_DATA"}
RET = {"v": "HLE_RET_VOID", "i": "HLE_RET_INT", "l": "HLE_RET_I64", "f": "HLE_RET_F64",
       "n": "HLE_RET_NORETURN", "u": "HLE_RET_X87_UNARY", "b": "HLE_RET_X87_BINARY"}


def stem(dll):
    s = dll.lower()
    return s[:-4] if s.endswith(".dll") else s


def cname(name):
    """Export name -> C identifier: every character outside [0-9A-Za-z_] becomes '_'. This is
    the rule the translator uses (recomp/sgrecomp/image.py imp_symbol); the two C++-mangled
    MSVCR90 exports become e.g. sg_imp_msvcr90__terminate__YAXXZ."""
    return re.sub(r"[^0-9A-Za-z_]", "_", name)


def implemented_shims():
    """Host symbols defined in runtime/hle/src/*.c, found in the preprocessed source so shims
    generated by macros count too. Needs clang (the Command Line Tools)."""
    found = set()
    src = os.path.join(ROOT, "runtime", "hle", "src")
    gen_h = os.path.join(ROOT, "runtime", "hle", "gen", "hle_imports.h")
    if not os.path.exists(gen_h):  # first run: the declarations are not needed to find definitions
        os.makedirs(os.path.dirname(gen_h), exist_ok=True)
        open(gen_h, "w").write('#include "hle.h"\n')
    inc = ["-I" + os.path.join(ROOT, "runtime", "include"), "-I" + os.path.join(ROOT, "runtime", "hle", "include"),
           "-I" + os.path.join(ROOT, "runtime", "hle", "gen")]
    pat = re.compile(r"void (sg_imp_\w+)\(sg_ctx \*\s*__restrict__ ctx, uint8_t \*mem\)\s*\{")
    for fn in sorted(os.listdir(src)):
        if fn.endswith(".c"):
            out = subprocess.run(["clang", "-E", "-P", "-std=c11"] + inc + [os.path.join(src, fn)],
                                 check=True, capture_output=True, text=True).stdout
            found.update(pat.findall(out))
    return found


def build():
    imports, dynamic = sigs.parse()
    data = json.load(open(os.path.join(ROOT, "data", "imports.json")))
    impl = implemented_shims()
    rows = []
    for rec in sorted(data["imports"], key=lambda r: int(r["iat"], 16)):
        name = rec["name"] or rec["ordinal_name_inferred"]
        sig = imports[(rec["dll"], name)]
        st = stem(rec["dll"])
        sfx = ("ord%d" % rec["ordinal"]) if rec["name"] is None else cname(name)
        sym = "sg_imp_%s_%s" % (st, sfx)
        argbytes = 4 * sig["slots"] if sig["cc"] in ("s", "t") else 0
        rows.append(dict(dll=rec["dll"], name=rec["name"], inferred=rec["ordinal_name_inferred"],
                         ordinal=rec["ordinal"] or 0, iat=int(rec["iat"], 16), sym=sym, stem=st, sfx=sfx,
                         cc=sig["cc"], slots=sig["slots"], varargs=sig["varargs"], ret=sig["ret"],
                         argbytes=argbytes, uses=rec["uses"], layer=rec["layer"], impl=sym in impl))
    by_key = {(r["stem"], r["name"] or r["inferred"]): r for r in rows}
    drows = []
    for dy in dynamic:
        st = stem(dy["module"])
        if dy["policy"] == "absent":
            sym = None
        elif (st, dy["name"]) in by_key:
            sym = by_key[(st, dy["name"])]["sym"]
        else:
            sym = "sg_imp_%s_%s" % (st, cname(dy["name"]))
        drows.append(dict(dy, stem=st, sym=sym, argbytes=4 * dy["slots"] if dy["cc"] in ("s", "t") else 0,
                          impl=(sym in impl) if sym else False,
                          shared=sym is not None and (st, dy["name"]) in by_key))
    return rows, drows


def emit(rows, drows):
    h = ["/* GENERATED by tools/hle/gen_thunks.py from data/imports.json and tools/hle/sigs.py.",
         " * Do not edit; rerun the generator. */",
         "#ifndef SPORE_HLE_IMPORTS_H", "#define SPORE_HLE_IMPORTS_H", '#include "hle.h"', "",
         "enum hle_import_index {"]
    for i, r in enumerate(rows):
        h.append("    HLE_IMP_%s_%s = %d," % (r["stem"], r["sfx"], i))
    h += ["    HLE_IMP_COUNT = %d" % len(rows), "};", ""]
    for r in rows:
        if r["cc"] != "d":
            h.append("SG_IMPORT(%s, %s); /* %s!%s */" % (r["stem"], r["sfx"], r["dll"], r["name"] or r["inferred"]))
    h.append("")
    h.append("/* Dynamically resolved names (GetProcAddress) that the runtime provides. */")
    for d in drows:
        if d["sym"] and not d["shared"]:
            h.append("SG_IMPORT(%s, %s); /* %s!%s */" % (d["stem"], cname(d["name"]), d["module"], d["name"]))
    h += ["", "#endif", ""]

    c = ["/* GENERATED by tools/hle/gen_thunks.py from data/imports.json and tools/hle/sigs.py.",
         " * Do not edit; rerun the generator. Hand-written shims live in runtime/hle/src/. */",
         '#include "hle_imports.h"', "",
         "sg_import hle_imports[%d] = {" % len(rows)]
    for r in rows:
        nm = '"%s"' % r["name"] if r["name"] else "0"
        fn = "0" if r["cc"] == "d" else r["sym"]
        c.append('    {"%s", %s, %d, %s, %d, 0x%08xu, 0, %s},' % (r["dll"], nm, r["ordinal"], CC[r["cc"]],
                                                              r["argbytes"], r["iat"], fn))
    c += ["};", "", "const hle_import_meta hle_import_info[%d] = {" % len(rows)]
    for r in rows:
        c.append('    {"%s", %s, %d, %d, %d},' % (r["sym"], RET[r["ret"]], int(r["varargs"]), r["slots"], int(r["impl"])))
    c += ["};", "const unsigned hle_import_count = %d;" % len(rows), ""]
    c.append("hle_dynamic hle_dynamics[%d] = {" % len(drows))
    for d in drows:
        c.append('    {"%s", "%s", %s, %d, %s, %d, %s, "%s", 0},' % (
            d["module"], d["name"], CC[d["cc"]], d["argbytes"], RET[d["ret"]], int(d["impl"]),
            d["sym"] or "0", d["reason"].replace('"', "'")))
    c += ["};", "const unsigned hle_dynamic_count = %d;" % len(drows), ""]
    c.append("/* ---- unimplemented stubs: log, then abort or return a default (hle_unimpl_policy) ---- */")
    for i, r in enumerate(rows):
        if r["cc"] == "d" or r["impl"]:
            continue
        c.append("__attribute__((weak)) SG_IMPORT(%s, %s) { hle_unimplemented(ctx, mem, %d); SG_RET(%d); }" % (
            r["stem"], r["sfx"], i, r["argbytes"]))
    for i, d in enumerate(drows):
        if d["sym"] and not d["shared"] and not d["impl"]:
            c.append("__attribute__((weak)) SG_IMPORT(%s, %s) { hle_unimplemented_dynamic(ctx, mem, %d); SG_RET(%d); }" % (
                d["stem"], cname(d["name"]), i, d["argbytes"]))
    c.append("")

    table = dict(
        generator="tools/hle/gen_thunks.py",
        abi="runtime/include/spore_guest.h section 7 (SG_IMPORT naming, sg_import)",
        note="cleanup_bytes is what the shim's SG_RET pops (stdcall/thiscall argument bytes, 0 for cdecl/x87). "
             "x87: u = ST0=f(ST0), b = ST1=f(ST1,ST0) then pop. ret: v void, i eax, l edx:eax, f ST(0), n noreturn.",
        imports=[dict(iat="0x%08x" % r["iat"], dll=r["dll"], name=r["name"] or r["inferred"],
                      by_ordinal=r["name"] is None, ordinal=r["ordinal"] or None, symbol=None if r["cc"] == "d" else r["sym"],
                      cc={"c": "cdecl", "s": "stdcall", "t": "thiscall", "x": "x87", "d": "data"}[r["cc"]],
                      slots=r["slots"], varargs=r["varargs"], cleanup_bytes=r["argbytes"], ret=r["ret"],
                      implemented=r["impl"], uses=r["uses"], layer=r["layer"]) for r in rows],
        dynamic=[dict(module=d["module"], name=d["name"], policy=d["policy"], symbol=d["sym"],
                      cc={"c": "cdecl", "s": "stdcall"}[d["cc"]], cleanup_bytes=d["argbytes"], ret=d["ret"],
                      implemented=d["impl"], reason=d["reason"]) for d in drows],
    )
    n_impl = sum(r["impl"] for r in rows)
    table["summary"] = dict(imports=len(rows), data_imports=sum(r["cc"] == "d" for r in rows),
                            implemented=n_impl, stubs=len(rows) - n_impl - sum(r["cc"] == "d" for r in rows),
                            implemented_uses=sum(r["uses"] for r in rows if r["impl"]),
                            total_uses=sum(r["uses"] for r in rows),
                            dynamic=len(drows), dynamic_provided=sum(d["policy"] == "provide" for d in drows),
                            dynamic_absent=sum(d["policy"] == "absent" for d in drows))
    return "\n".join(h), "\n".join(c), json.dumps(table, indent=1) + "\n"


def main():
    rows, drows = build()
    hs, cs, js = emit(rows, drows)
    outs = {os.path.join(ROOT, "runtime", "hle", "gen", "hle_imports.h"): hs,
            os.path.join(ROOT, "runtime", "hle", "gen", "hle_imports.c"): cs,
            os.path.join(ROOT, "data", "hle", "imports-table.json"): js}
    if "--check" in sys.argv:
        stale = [p for p, t in outs.items() if not os.path.exists(p) or open(p).read() != t]
        print("stale:" if stale else "up to date", *stale)
        sys.exit(1 if stale else 0)
    for p, t in outs.items():
        os.makedirs(os.path.dirname(p), exist_ok=True)
        open(p, "w").write(t)
    print(json.loads(js)["summary"])


if __name__ == "__main__":
    main()
