#!/usr/bin/env python3
"""Regenerates src/sgp_list.h: every SG_IMPORT this package defines, with the clean-up bytes from
the generated import table (runtime/hle/gen/hle_imports.c). --check fails if the file is stale or an
import is missing from the table. Our own code; reads no game bytes.

Usage:   python3 runtime/platform/guest/gen_list.py [--check]   (`make -C runtime/platform/guest check-gen`)
When:    after adding or removing an SG_IMPORT in runtime/platform/guest/src."""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
tab = open(os.path.join(ROOT, "runtime", "hle", "gen", "hle_imports.c")).read()
bytes_of = {}
for m in re.finditer(r'\{"[^"]+", (?:"[^"]+"|0), \d+, SG_CC_\w+, (\d+), 0x[0-9a-f]+u, 0, (sg_imp_\w+)\}', tab):
    bytes_of[m.group(2)] = int(m.group(1))
for m in re.finditer(r'\{"[^"]+", "[^"]+", SG_CC_\w+, (\d+), HLE_RET_\w+, \d, (sg_imp_\w+),', tab):
    bytes_of[m.group(2)] = int(m.group(1))
rows, missing = [], []
for f in sorted(os.listdir(os.path.join(HERE, "src"))):
    if not f.endswith(".c"):
        continue
    for dll, name in re.findall(r'^SG_IMPORT\((\w+), (\w+)\)', open(os.path.join(HERE, "src", f)).read(), re.M):
        sym = "sg_imp_%s_%s" % (dll, name)
        if sym not in bytes_of:
            missing.append(sym)
            continue
        rows.append("SGP_SHIM(%s, %s, %d)" % (dll, name, bytes_of[sym]))
out = "/* GENERATED by runtime/platform/guest/gen_list.py: the imports this package defines. */\n" + "\n".join(rows) + "\n"
p = os.path.join(HERE, "src", "sgp_list.h")
if missing:
    sys.exit("not in the import table: " + ", ".join(missing))
if "--check" in sys.argv:
    sys.exit(0 if os.path.exists(p) and open(p).read() == out else "src/sgp_list.h is stale")
open(p, "w").write(out)
print("%d imports -> %s" % (len(rows), os.path.relpath(p, ROOT)))
