/* loader.c -- guest window, PE section mapping and page protections.
 * Spec: runtime-abi.md 3.1-3.3, docs/design/image-linker.md. No game bytes here: the bytes come from
 * the user's exe at run time, or from a copy embedded in the (build/-only) binary by tools/link. */
