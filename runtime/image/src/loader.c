uint8_t *sg_image_mem;
sg_image_info sg_image;

/* Generated by tools/link/gen_link.py: image_embed.s (blob) or image_none.c (size 0). */
extern const uint8_t sg_embedded_image[];
extern const uint32_t sg_embedded_image_size;
#ifndef SG_REPO_ROOT
#define SG_REPO_ROOT "."
#endif

static double now_ms(void) {
    struct timespec ts;
    clock_gettime(CLOCK_MONOTONIC, &ts);
    return ts.tv_sec * 1e3 + ts.tv_nsec / 1e6;
}

/* ---- window --------------------------------------------------------------------------------- */

uint8_t *sg_image_window_reserve(void) {
    void *p;
    if (sg_image_mem) return sg_image_mem;
    p = mmap(NULL, SG_WINDOW_SIZE + SG_WINDOW_GUARD, PROT_NONE, MAP_PRIVATE | MAP_ANON | MAP_NORESERVE, -1, 0);
    if (p == MAP_FAILED) {
        fprintf(stderr, "image: cannot reserve the 4 GiB guest window: %s\n", strerror(errno));
        return NULL;
    }
    sg_image_mem = (uint8_t *)p;
    return sg_image_mem;
}

int sg_image_window_commit(uint32_t lo, uint32_t hi, int prot) {
    uint64_t a = lo & ~(uint64_t)(SG_HOST_PAGE - 1u), b = ((uint64_t)hi + SG_HOST_PAGE - 1u) & ~(uint64_t)(SG_HOST_PAGE - 1u);
    if (!sg_image_mem || b <= a) return -1;
    if (mprotect(sg_image_mem + a, (size_t)(b - a), prot)) {
        fprintf(stderr, "image: mprotect(0x%08llx-0x%08llx, %d) failed: %s\n", (unsigned long long)a,
                (unsigned long long)b, prot, strerror(errno));
        return -1;
    }
    return 0;
}

/* ---- fault report (runtime-abi 3.3: SIGBUS on arm64 for PROT_NONE pages) ------------------- */

static void fault_handler(int sig, siginfo_t *si, void *uc) {
    char buf[256];
    uint8_t *a = (uint8_t *)si->si_addr;
    int n;
    (void)uc;
    if (sg_image_mem && a >= sg_image_mem && a < sg_image_mem + SG_WINDOW_SIZE + SG_WINDOW_GUARD) {
        uint64_t g = (uint64_t)(a - sg_image_mem);
        uint32_t eip = sg_self ? sg_self->ctx.eip : 0, esp = sg_self ? sg_self->ctx.esp : 0;
        n = snprintf(buf, sizeof buf, "\nspore: guest memory fault (signal %d) at guest 0x%08llx%s; last ret eip=0x%08x esp=0x%08x\n",
                     sig, (unsigned long long)g, g >= SG_WINDOW_SIZE ? " (guard past 4 GiB)" : "", eip, esp);
    } else {
        n = snprintf(buf, sizeof buf, "\nspore: host fault (signal %d) at %p (outside the guest window)\n", sig, (void *)a);
    }
    if (n > 0) write(2, buf, (size_t)n);
    signal(sig, SIG_DFL);
    raise(sig);
}

void sg_image_install_fault_handler(void) {
    static int done;
    static uint8_t altstack[64 * 1024];
    stack_t ss;
    struct sigaction sa;
    if (done) return;
    done = 1;
    ss.ss_sp = altstack;
    ss.ss_size = sizeof altstack;
    ss.ss_flags = 0;
    sigaltstack(&ss, NULL);
    memset(&sa, 0, sizeof sa);
    sa.sa_sigaction = fault_handler;
    sa.sa_flags = SA_SIGINFO | SA_ONSTACK;
    sigemptyset(&sa.sa_mask);
    sigaction(SIGSEGV, &sa, NULL);
    sigaction(SIGBUS, &sa, NULL);
}

/* ---- PE headers ------------------------------------------------------------------------------ */

static uint32_t rd32(const uint8_t *p) { uint32_t v; memcpy(&v, p, 4); return v; }
static uint16_t rd16(const uint8_t *p) { uint16_t v; memcpy(&v, p, 2); return v; }

static int prot_of(uint32_t ch) {
    int p = 0;
    if (ch & 0x40000000u) p |= PROT_READ;  /* IMAGE_SCN_MEM_READ */
    if (ch & 0x80000000u) p |= PROT_WRITE; /* IMAGE_SCN_MEM_WRITE; execute is never granted: code is translated */
    return p ? p : PROT_READ;
}

/* Parses the headers at `h` (n bytes available) into sg_image. Returns 0 if the PE is the image the
 * runtime ABI was written for (base 0x400000, SizeOfImage and entry as in spore_guest.h). */
static int parse_headers(const uint8_t *h, size_t n) {
    uint32_t pe, opt, nsec, i;
    if (n < 0x400 || h[0] != 'M' || h[1] != 'Z') return -1;
    pe = rd32(h + 0x3c);
    if (pe + 0xf8 > n || memcmp(h + pe, "PE\0\0", 4)) return -1;
    nsec = rd16(h + pe + 6);
    opt = rd16(h + pe + 20);
    sg_image.image_base = rd32(h + pe + 24 + 28);
    sg_image.entry = sg_image.image_base + rd32(h + pe + 24 + 16);
    sg_image.size_of_image = rd32(h + pe + 24 + 56);
    if (nsec > 16 || pe + 24 + opt + 40 * nsec > n) return -1;
    sg_image.nsections = nsec;
    for (i = 0; i < nsec; i++) {
        const uint8_t *s = h + pe + 24 + opt + 40 * i;
        sg_image_section *d = &sg_image.sec[i];
        memcpy(d->name, s, 8);
        d->name[8] = 0;
        d->vsize = rd32(s + 8);
        d->va = sg_image.image_base + rd32(s + 12);
        d->raw_size = rd32(s + 16);
        d->raw_off = rd32(s + 20);
        d->characteristics = rd32(s + 36);
        d->prot = prot_of(d->characteristics);
    }
    if (sg_image.image_base != SG_IMAGE_BASE || sg_image.size_of_image != SG_IMAGE_SIZE ||
        sg_image.entry != SG_IMAGE_ENTRY) {
        fprintf(stderr, "image: unexpected PE (base 0x%x size 0x%x entry 0x%x); this runtime is built for GOG EP1 SporeApp.exe\n",
                sg_image.image_base, sg_image.size_of_image, sg_image.entry);
        return -1;
    }
    return 0;
}

static void hex32(const unsigned char *d, char *out) {
    static const char *x = "0123456789abcdef";
    for (int i = 0; i < 32; i++) { out[2 * i] = x[d[i] >> 4]; out[2 * i + 1] = x[d[i] & 15]; }
    out[64] = 0;
}

/* ---- sources ----------------------------------------------------------------------------------- */

static int load_from_file(uint8_t *mem, const char *path, int verify) {
    int fd = open(path, O_RDONLY);
    struct stat st;
    const uint8_t *f;
    unsigned i;
    double t0;
    if (fd < 0) {
        fprintf(stderr, "image: cannot open %s: %s (set SPORE_EXE or pass --exe)\n", path, strerror(errno));
        return -1;
    }
    if (fstat(fd, &st) || st.st_size < 0x400) { close(fd); return -1; }
    t0 = now_ms();
    f = (const uint8_t *)mmap(NULL, (size_t)st.st_size, PROT_READ, MAP_PRIVATE, fd, 0);
    close(fd);
    if (f == MAP_FAILED) return -1;
    if (verify) {
        unsigned char md[CC_SHA256_DIGEST_LENGTH];
        char hex[65];
        double h0 = now_ms();
        CC_SHA256(f, (CC_LONG)st.st_size, md);
        hex32(md, hex);
        sg_image.hash_ms = now_ms() - h0;
        sg_image.sha_ok = !strcmp(hex, SG_IMAGE_SHA256);
        if (!sg_image.sha_ok) {
            fprintf(stderr, "image: %s has SHA-256 %s, expected %s (GOG EP1 SporeApp.exe)\n", path, hex, SG_IMAGE_SHA256);
            munmap((void *)f, (size_t)st.st_size);
            return -1;
        }
    }
    if (parse_headers(f, (size_t)st.st_size)) { munmap((void *)f, (size_t)st.st_size); return -1; }
    if (sg_image_window_commit(SG_IMAGE_BASE, SG_IMAGE_MAPPED_END, PROT_READ | PROT_WRITE)) return -1;
    memcpy(mem + SG_IMAGE_BASE, f, 0x1000); /* headers (SizeOfHeaders 0x400, rest of the page zero) */
    memset(mem + SG_IMAGE_BASE + 0x400, 0, 0x1000 - 0x400);
    for (i = 0; i < sg_image.nsections; i++) {
        const sg_image_section *s = &sg_image.sec[i];
        uint32_t n = s->raw_size < s->vsize ? s->raw_size : s->vsize;
        if ((uint64_t)s->raw_off + n > (uint64_t)st.st_size || s->va + s->vsize > SG_IMAGE_MAPPED_END) {
            fprintf(stderr, "image: section %s out of bounds\n", s->name);
            munmap((void *)f, (size_t)st.st_size);
            return -1;
        }
        memcpy(mem + s->va, f + s->raw_off, n); /* the rest of the section stays zero (fresh pages) */
    }
    munmap((void *)f, (size_t)st.st_size);
    sg_image.load_ms = now_ms() - t0;
    snprintf(sg_image.path, sizeof sg_image.path, "%s", path);
    return 0;
}

int sg_image_embedded(void) { return sg_embedded_image_size != 0; }

static int load_embedded(uint8_t *mem, int use_mmap) {
    uint32_t size = sg_embedded_image_size;
    double t0 = now_ms();
    if (!size) {
        fprintf(stderr, "image: this binary has no embedded image (link with tools/link/build.py --embed)\n");
        return -1;
    }
    if (size != SG_IMAGE_MAPPED_END - SG_IMAGE_BASE) {
        fprintf(stderr, "image: embedded image is 0x%x bytes, expected 0x%x\n", size, SG_IMAGE_MAPPED_END - SG_IMAGE_BASE);
        return -1;
    }
    if (use_mmap) {
        /* Zero copy: the blob sits 16 KiB-aligned in its own segment, so map that part of our own file. */
        const struct section_64 *sec = getsectbyname("__SPIMG", "__image");
        char exe[4096];
        uint32_t cap = sizeof exe;
        int fd;
        void *p;
        if (!sec || (sec->offset & (SG_HOST_PAGE - 1u)) || _NSGetExecutablePath(exe, &cap)) {
            fprintf(stderr, "image: embedded image not page-aligned in the file; falling back to a copy\n");
            return load_embedded(mem, 0);
        }
        fd = open(exe, O_RDONLY);
        if (fd < 0) return load_embedded(mem, 0);
        p = mmap(mem + SG_IMAGE_BASE, size, PROT_READ | PROT_WRITE, MAP_FIXED | MAP_PRIVATE, fd, (off_t)sec->offset);
        close(fd);
        if (p != (void *)(mem + SG_IMAGE_BASE)) {
            fprintf(stderr, "image: mmap of the embedded image failed: %s\n", strerror(errno));
            return -1;
        }
        snprintf(sg_image.path, sizeof sg_image.path, "%s (embedded, mapped at file offset 0x%x)", exe, sec->offset);
    } else {
        if (sg_image_window_commit(SG_IMAGE_BASE, SG_IMAGE_MAPPED_END, PROT_READ | PROT_WRITE)) return -1;
        memcpy(mem + SG_IMAGE_BASE, sg_embedded_image, size);
        snprintf(sg_image.path, sizeof sg_image.path, "(embedded, copied)");
    }
    sg_image.load_ms = now_ms() - t0;
    return parse_headers(mem + SG_IMAGE_BASE, 0x1000);
}

static const char *default_exe(const char *given) {
    static char buf[1200];
    const char *e = getenv("SPORE_EXE");
    if (given) return given;
    if (e && *e) return e;
    snprintf(buf, sizeof buf, "%s/game/SporebinEP1/SporeApp.exe", SG_REPO_ROOT);
    return buf;
}

int sg_image_load(uint8_t *mem, enum sg_image_source src, const char *exe_path, int verify_sha) {
    int r;
    memset(&sg_image, 0, sizeof sg_image);
    sg_image.source = src;
    sg_image.sha_ok = -1;
    if (src == SG_IMAGE_FROM_FILE) r = load_from_file(mem, default_exe(exe_path), verify_sha);
    else r = load_embedded(mem, src == SG_IMAGE_EMBED_MMAP);
    if (r) return r;
    /* Loader duties that are not section copies (runtime-abi 7.2): the TLS index variable is 0. The
     * callback array at 0x13eb0b4 is empty [obs, the PE TLS directory], so nothing else is called. */
    sg_st32(mem, SG_IMAGE_TLS_INDEX_VA, 0);
    return 0;
}

int sg_image_protect(uint8_t *mem) {
    /* Per host page: union of the protections of every section (and the headers) touching it. */
    enum { NPAGES = (SG_IMAGE_MAPPED_END - SG_IMAGE_BASE) / SG_HOST_PAGE };
    static unsigned char prot[NPAGES];
    unsigned i, p, start;
    double t0 = now_ms();
    (void)mem;
    memset(prot, 0, sizeof prot);
    prot[0] = PROT_READ; /* headers */
    for (i = 0; i < sg_image.nsections; i++) {
        const sg_image_section *s = &sg_image.sec[i];
        uint32_t lo = (s->va - SG_IMAGE_BASE) / SG_HOST_PAGE;
        uint32_t hi = (s->va + (s->vsize ? s->vsize : 1u) - 1u - SG_IMAGE_BASE) / SG_HOST_PAGE;
        for (p = lo; p <= hi && p < NPAGES; p++) prot[p] |= (unsigned char)s->prot;
    }
    for (p = 0; p < NPAGES; p++)
        if (!prot[p]) prot[p] = PROT_READ; /* gap pages inside SizeOfImage: readable zeros, as on Windows */
    for (start = 0, p = 1; p <= NPAGES; p++) {
        if (p == NPAGES || prot[p] != prot[start]) {
            if (sg_image_window_commit(SG_IMAGE_BASE + start * SG_HOST_PAGE, SG_IMAGE_BASE + p * SG_HOST_PAGE, prot[start]))
                return -1;
            start = p;
        }
    }
    sg_image.protect_ms = now_ms() - t0;
    return 0;
}
