"""Assemble our own test shaders (*.asm) with our d3dbc assembler (tools/shaders/d3dbc.py) into a C header.
Used by this package's tests (test_readback, test_conformance), pipeline/Makefile and shader/tests/crosscheck.py.

Usage: python3 -P gen_shaders.py <shader dir> <out header>
Every blob is round-tripped through d3dbc.parse/disassemble as a check.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools", "shaders"))
import d3dbc  # noqa: E402


def main(src, out):
    lines = ["// Generated by runtime/d3d9metal/tests/gen_shaders.py from our own .asm files.",
             "#pragma once", "#include <stdint.h>", ""]
    for fn in sorted(os.listdir(src)):
        if not fn.endswith(".asm"):
            continue
        toks = d3dbc.assemble(open(os.path.join(src, fn)).read())
        sh = d3dbc.parse(toks)
        assert d3dbc.assemble(d3dbc.disassemble(sh)) == list(toks), fn
        name = fn[:-4]
        lines.append(f"static const uint32_t k_{name}[] = {{")
        for i in range(0, len(toks), 8):
            lines.append("  " + ", ".join(f"0x{t:08x}" for t in toks[i:i + 8]) + ",")
        lines.append("};")
        print(f"{name}: {len(toks)} tokens")
    open(out, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
