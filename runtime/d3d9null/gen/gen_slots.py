#!/usr/bin/env python3
"""Generate runtime/d3d9null/src/d3d9_slots.h from tools/d3d9/comtypes.py (the d3d9.h layouts)
and data/graphics-d3d9-usage.json (the 103 methods the game calls, with their call sites, measured from the exe).

Usage:   python3 -P runtime/d3d9null/gen/gen_slots.py [--check]   (`make -C runtime/d3d9null gen` / `check-gen`)
When:    after changing tools/d3d9/comtypes.py; `make test` runs --check.
When the usage file is absent, the list of called methods already in d3d9_slots.h is kept, so --check (run by
`make test`) still verifies the slot layouts against comtypes.py.
"""
import json
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "tools", "d3d9"))
import comtypes  # noqa: E402

OUT = os.path.join(ROOT, "runtime", "d3d9null", "src", "d3d9_slots.h")
IFACES = ["IDirect3D9", "IDirect3DDevice9", "IDirect3DSwapChain9", "IDirect3DTexture9", "IDirect3DCubeTexture9",
          "IDirect3DVolumeTexture9", "IDirect3DSurface9", "IDirect3DVolume9", "IDirect3DVertexBuffer9",
          "IDirect3DIndexBuffer9", "IDirect3DVertexDeclaration9", "IDirect3DVertexShader9", "IDirect3DPixelShader9",
          "IDirect3DQuery9", "IDirect3DStateBlock9", "ID3DXBuffer"]


def used_from_header():
    """The (interface, method, slot, sites) rows of the d3d9_used[] table in the current d3d9_slots.h."""
    rows = re.findall(r'^    \{"(\w+)", "(\w+)", (\d+), (\d+)\},$', open(OUT).read(), re.M)
    return [(i, m, int(s), int(n)) for i, m, s, n in rows]


def main():
    usage_path = os.path.join(ROOT, "data", "graphics-d3d9-usage.json")
    usage = json.load(open(usage_path))["interfaces"] if os.path.exists(usage_path) else None
    out = ["/* GENERATED by runtime/d3d9null/gen/gen_slots.py from tools/d3d9/comtypes.py and",
           " * data/graphics-d3d9-usage.json. Do not edit. */", "#ifndef D3D9_SLOTS_H", "#define D3D9_SLOTS_H", ""]
    used = []
    for name in IFACES:
        short = comtypes.SHORT[name]
        t = comtypes.IFACES[name]
        out.append("/* %s: %d slots */" % (name, len(t)))
        out.append("enum { %s_NSLOTS = %d };" % (short.upper(), len(t)))
        out.append("enum {")
        for i, (m, _n) in enumerate(t):
            out.append("    S_%s_%s = %d," % (short, m, i))
        out.append("};")
        out.append("enum { /* stdcall arguments after `this` */")
        for m, n in t:
            out.append("    A_%s_%s = %d," % (short, m, n))
        out.append("};")
        out.append("static const char *const %s_names[%d] = {%s};" % (short.lower(), len(t), ", ".join('"%s"' % m for m, _ in t)))
        out.append("static const uint8_t %s_args[%d] = {%s};" % (short.lower(), len(t), ", ".join(str(n) for _, n in t)))
        out.append("")
        if usage is not None:
            for m in usage.get(name, {}).get("methods", []):
                used.append((name, m["method"], m["slot"], len(m["sites"])))
    if usage is None:
        used = used_from_header()
    out.append("/* The %d (interface, method) pairs the game calls, with their call-site counts [obs]. */" % len(used))
    out.append("typedef struct d3d9_used_method { const char *iface, *method; unsigned slot, sites; } d3d9_used_method;")
    out.append("static const d3d9_used_method d3d9_used[%d] = {" % len(used))
    for u in used:
        out.append('    {"%s", "%s", %d, %d},' % u)
    out.append("};")
    out.append("#define D3D9_USED_METHODS %d" % len(used))
    out.append("#define D3D9_USED_SITES %d" % sum(u[3] for u in used))
    out.append("")
    out.append("#endif")
    text = "\n".join(out) + "\n"
    if "--check" in sys.argv:
        if open(OUT).read() != text:
            sys.exit("d3d9_slots.h is stale: run runtime/d3d9null/gen/gen_slots.py")
        return
    open(OUT, "w").write(text)
    print("wrote %s: %d interfaces, %d used methods, %d sites" % (os.path.relpath(OUT, ROOT), len(IFACES), len(used),
                                                                 sum(u[3] for u in used)))


if __name__ == "__main__":
    main()
